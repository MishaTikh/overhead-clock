static char fold(char c) {
    unsigned char u = (unsigned char)c;
    if (u >= 'a' && u <= 'z') return (char)(u - 32);
    if (u < 0x20 || u > 0x5A) return '?';
    return (char)u;
}

// strip UTF-8 accents crudely: drop continuation bytes, map lead byte to '?'-free fallback
static std::string ascii(const std::string& s) {
    std::string o;
    for (size_t i = 0; i < s.size(); i++) {
        unsigned char c = s[i];
        if (c < 0x80) { o += (char)c; continue; }
        if (c == 0xC3 && i + 1 < s.size()) {  // Latin-1 supplement: map common accented letters
            unsigned char d = s[++i];
            const char* map = "AAAAAAACEEEEIIIIDNOOOOOxOUUUUYPsaaaaaaaceeeeiiiidnooooo/ouuuuypy";
            if (d >= 0x80 && d <= 0xBF) o += map[d - 0x80];
            continue;
        }
        while (i + 1 < s.size() && (((unsigned char)s[i + 1]) & 0xC0) == 0x80) i++;
    }
    return o;
}

std::vector<uint8_t> text_columns(const std::string& text) {
    std::vector<uint8_t> cols;
    for (char raw : ascii(text)) {
        char c = fold(raw);
        if (c == ' ') {
            cols.insert(cols.end(), 3, 0);
            continue;
        }
        const uint8_t* g = BIG[c - 0x20];
        int lo = 0, hi = 4;
        while (lo < 5 && !g[lo]) lo++;
        while (hi > lo && !g[hi]) hi--;
        if (lo >= 5) { lo = 0; hi = 0; }
        for (int x = lo; x <= hi; x++) cols.push_back(g[x]);
        cols.push_back(0);
    }
    if (!cols.empty() && cols.back() == 0) cols.pop_back();
    return cols;
}

void Marquee::set_text(const std::string& text, double now, float speed) {
    speed_ = speed;
    if (text == text_) return;
    text_ = text;
    t0_ = now;
    cols_ = text_columns(text);
}

// Always a big-letter marquee: show the start of the text, hold briefly, then scroll left and repeat.
double Marquee::seconds_for(int cycles) const {
    int n = (int)cols_.size();
    int cycle = n + 12 > MATRIX_W + 4 ? n + 12 : MATRIX_W + 4;
    return SCROLL_HOLD_S + cycles * (double)cycle / (speed_ > 0 ? speed_ : S.scroll_speed);
}

void Marquee::frame(double now, uint8_t* out) const {
    const int w = MATRIX_W, gap = 12;
    int n = (int)cols_.size();
    for (int i = 0; i < w; i++) out[i] = 0;
    if (!n) return;
    int cycle = n + gap > w + 4 ? n + gap : w + 4;   // short names still scroll fully off before repeating
    double t = now - t0_ - SCROLL_HOLD_S;
    int off = t > 0 ? ((int)(t * (speed_ > 0 ? speed_ : S.scroll_speed))) % cycle : 0;
    for (int i = 0; i < w; i++) {
        int k = (off + i) % cycle;
        out[i] = k < n ? cols_[k] : 0;
    }
}

