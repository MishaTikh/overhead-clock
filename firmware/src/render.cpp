// "9:45" (12 h) or "21:45" (24 h), big font, centered; colon blinks when colon_on is false.
void clock_frame(int hour24, int minute, bool colon_on, bool h24, uint8_t* out) {
    char hh[4], mm[4];
    int h = h24 ? hour24 : ((hour24 + 11) % 12 + 1);
    snprintf(hh, sizeof(hh), h24 ? "%02d" : "%d", h);
    snprintf(mm, sizeof(mm), "%02d", minute);
    std::vector<uint8_t> cols = text_columns(hh);
    cols.push_back(0);
    cols.push_back(colon_on ? 0x14 : 0x00);  // ':' column
    cols.push_back(0);
    std::vector<uint8_t> m = text_columns(mm);
    cols.insert(cols.end(), m.begin(), m.end());
    for (int i = 0; i < MATRIX_W; i++) out[i] = 0;
    int pad = ((int)MATRIX_W - (int)cols.size()) / 2;
    for (size_t i = 0; i < cols.size() && pad + (int)i < MATRIX_W; i++) out[pad + i] = cols[i];
}

