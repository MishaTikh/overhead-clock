"""Generate firmware/src/timezones_data.h: IANA time zone name -> POSIX TZ string.

The ESP32 needs POSIX TZ strings; the address lookup returns IANA names (e.g. America/Chicago).
The POSIX string is the footer of each zone's TZif file in the tz database (public domain),
read here from the `tzdata` Python package.

    pip install tzdata
    python tools/gen_timezones.py
"""
import importlib.resources
import os
import zoneinfo

OUT = os.path.join(os.path.dirname(__file__), "..", "firmware", "src", "timezones_data.h")
REGIONS = ("Africa/", "America/", "Antarctica/", "Asia/", "Atlantic/", "Australia/", "Europe/", "Indian/", "Pacific/")


def posix_tz(name):
    data = importlib.resources.files("tzdata.zoneinfo").joinpath(name).read_bytes()
    return data.rstrip(b"\n").rsplit(b"\n", 1)[-1].decode()


def main():
    zones = sorted(z for z in zoneinfo.available_timezones() if z.startswith(REGIONS)) + ["UTC"]
    lines = ["// Generated by tools/gen_timezones.py from the tz database (public domain). Do not edit.",
             "#pragma once", "struct TzRec { const char* name; const char* posix; };", "static const TzRec TIMEZONES[] = {"]
    n = 0
    for z in zones:
        p = posix_tz(z)
        if p:
            lines.append('  {"%s", "%s"},' % (z, p))
            n += 1
    lines += ["};", "static const int TIMEZONE_COUNT = sizeof(TIMEZONES) / sizeof(TIMEZONES[0]);", ""]
    open(OUT, "w", newline="\n").write("\n".join(lines))
    print(f"{n} time zones -> {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
