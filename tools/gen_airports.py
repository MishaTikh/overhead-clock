"""Generate firmware/src/airports_data.h from OurAirports (public domain data).

Keeps large and medium airports with scheduled passenger service and an IATA code (what the
clock needs to pick the nearest airport), with their ICAO code (for weather reports) and the
ends of their open, paved runways longer than 4,000 ft (to work out which way planes land).

    python tools/gen_airports.py
"""
import csv
import io
import os
import unicodedata
import urllib.request

URL = "https://davidmegginson.github.io/ourairports-data/airports.csv"
RUNWAYS_URL = "https://davidmegginson.github.io/ourairports-data/runways.csv"
OUT = os.path.join(os.path.dirname(__file__), "..", "firmware", "src", "airports_data.h")


def ascii_only(s):
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()
    return s.replace("\\", "").replace('"', "'")


def fetch(url):
    return urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "overhead-clock tools"})).read().decode("utf-8")


def runways_by_airport():
    out = {}
    for r in csv.DictReader(io.StringIO(fetch(RUNWAYS_URL))):
        try:
            if r["closed"] == "1" or int(r["length_ft"] or 0) < 4000:
                continue
            ends = [float(r[k]) for k in ("le_latitude_deg", "le_longitude_deg", "he_latitude_deg", "he_longitude_deg")]
        except ValueError:
            continue
        le, he = r["le_ident"].strip()[:3], r["he_ident"].strip()[:3]
        out.setdefault(r["airport_ident"], []).append((le, he, *ends))
    return out


def main():
    rwys = runways_by_airport()
    rows = []
    for r in csv.DictReader(io.StringIO(fetch(URL))):
        if r["type"] not in ("large_airport", "medium_airport") or r["scheduled_service"] != "yes":
            continue
        iata = r["iata_code"].strip().upper()
        if len(iata) != 3 or not iata.isalnum():
            continue
        city = ascii_only(r["municipality"] or r["name"])[:28]
        icao = (r["icao_code"] or r["gps_code"] or r["ident"]).strip().upper()
        icao = icao if len(icao) == 4 and icao.isalnum() else ""
        rows.append((iata, icao, float(r["latitude_deg"]), float(r["longitude_deg"]), city,
                     r["type"] == "large_airport", rwys.get(r["ident"], [])))
    rows.sort()
    runway_lines, airport_lines = [], []
    for iata, icao, la, lo, c, lg, rw in rows:
        airport_lines.append('  {"%s", "%s", %.4f, %.4f, "%s", %s, %d, %d},' % (
            iata, icao, la, lo, c, "true" if lg else "false", len(runway_lines), len(rw)))
        for le, he, a, b, c2, d in rw:
            runway_lines.append('  {"%s", "%s", %.5f, %.5f, %.5f, %.5f},' % (le, he, a, b, c2, d))
    lines = [
        "// Generated by tools/gen_airports.py from OurAirports (public domain). Do not edit.",
        "#pragma once",
        "#include <stdint.h>",
        "struct RunwayRec { char le[4], he[4]; float le_lat, le_lon, he_lat, he_lon; };",
        "struct AirportRec { char iata[4]; char icao[5]; float lat, lon; const char* city; bool large; uint16_t rwy_first; uint8_t rwy_count; };",
        "static const RunwayRec RUNWAYS[] = {",
    ] + runway_lines + ["};", "static const AirportRec AIRPORTS[] = {"] + airport_lines + [
        "};", "static const int AIRPORT_COUNT = sizeof(AIRPORTS) / sizeof(AIRPORTS[0]);", ""]
    open(OUT, "w", newline="\n").write("\n".join(lines))
    print(f"{len(rows)} airports, {len(runway_lines)} runways -> {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
