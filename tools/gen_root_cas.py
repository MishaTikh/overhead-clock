import certifi, re, sys
pem = open(certifi.where(), encoding="utf-8").read()
blocks = re.findall(r'# Label: "(.*?)".*?(-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----)', pem, re.S)
want = ["ISRG Root X1", "ISRG Root X2", "GTS Root R1", "GTS Root R4", "DigiCert Global Root G2",
        "DigiCert Global Root CA", "USERTrust RSA Certification Authority"]
found = {l: c for l, c in blocks if l in want}
NL = chr(92) + "n"
lines = ["// Root certificates the clock trusts (from the Mozilla CA bundle via certifi). Generated by tools/gen_root_cas.py.",
         "// ISRG (Let's Encrypt): api.adsb.lol, api.adsbdb.com, www.mspairport.com, nominatim.openstreetmap.org,",
         "//   api.open-meteo.com. Google Trust Services: vrs-standing-data.adsb.lol. DigiCert: geocoding.geo.census.gov,",
         "//   aviationweather.gov. USERTrust and the second roots are spares in case a service switches CA.",
         "// If a feature stops working after a service changes CA, add its root here and regenerate.",
         "#pragma once", "static const char ROOT_CAS[] ="]
for w in want:
    lines.append("    // " + w)
    for l in found[w].splitlines():
        lines.append('    "' + l + NL + '"')
lines.append("    ;")
open(sys.argv[1], "w", newline="\n").write("\n".join(lines) + "\n")
